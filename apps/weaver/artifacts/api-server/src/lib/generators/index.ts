const BUILDERS: Record<string, Builder> = {
  primer: buildPrimer,
  carbon: buildCarbon,
  "material-web": buildMaterial,
  fluent: buildFluent,
  cloudscape: buildCloudscape,
  geist: buildGeist,
  radix: buildRadix,
  atlassian: buildAtlassian,
  polaris: buildPolaris,
  spectrum: buildSpectrum,
};

export function generateForSystem(
  system: DesignSystemEntry,
  p: ResolvedProfile,
  projectName: string,
): GeneratedPackage {
  const builder = BUILDERS[system.id];
  if (!builder) {
    throw new Error(`No generator implemented for design system "${system.id}"`);
  }
  const out = builder(p, projectName);
  const tokens = tokensJsonFile(p, system);
  const readme = readmeFile(
    p,
    system,
    projectName,
    [
      ...out.fileSummaries,
      { path: tokens.path, purpose: "Portable design tokens (W3C community format)" },
    ],
    out.installSteps,
  );
  const deterministicNotes = [
    `Mapping summary for ${system.name} (${system.organization}):`,
    ...out.mappingHighlights.map((m) => `- ${m}`),
    `- Typography: headings "${p.typography.headingFont}" (${p.typography.headingWeight}), body "${p.typography.bodyFont}" (${p.typography.bodyWeight}), base ${p.typography.baseSizePx}px.`,
    `- Spacing base ${p.spacing.basePx}px (${p.spacing.density}); radius ${p.radius.basePx}px (${p.radius.style}); shadows ${p.shadows.style}.`,
    "",
    "Apply:",
    ...out.installSteps.map((s) => `- ${s}`),
  ].join("\n");
  return {
    files: [...out.themeFiles, tokens, readme],
    deterministicNotes,
  };
}
